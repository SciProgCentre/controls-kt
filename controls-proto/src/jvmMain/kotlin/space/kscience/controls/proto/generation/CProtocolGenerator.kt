    private fun generateHeader(context: CContext): String = buildString {
        appendLine("/* Generated by controls-proto. Do not edit by hand. */")
        appendLine("#ifndef ${context.includeGuard}")
        appendLine("#define ${context.includeGuard}")
        appendLine()
        appendLine("#include <stdbool.h>")
        appendLine("#include <stddef.h>")
        appendLine("#include <stdint.h>")
        appendLine()
        appendLine("#ifdef __cplusplus")
        appendLine("extern \"C\" {")
        appendLine("#endif")
        appendLine()
        appendErrorCodes(context)
        appendLine("typedef struct ${context.moduleName}_string {")
        appendLine("    const char *data;")
        appendLine("    size_t size;")
        appendLine("} ${context.moduleName}_string_t;")
        appendLine()
        context.properties.forEach { property ->
            val model = property.type as? ProtocolPropertyType.StructuredMeta ?: return@forEach
            appendStructuredStructs(context, model.model.rootNode, listOf(model.model.rootNode.name))
        }
        appendRequestTypes(context)
        appendResponseTypes(context)
        appendLine("typedef ${context.moduleName}_response_t (*${context.moduleName}_request_handler_t)(")
        appendLine("    const ${context.moduleName}_request_t *request,")
        appendLine("    void *user_data")
        appendLine(");")
        appendLine()
        appendLine("int ${context.moduleName}_handle_message(")
        appendLine("    const uint8_t *input,")
        appendLine("    size_t input_size,")
        appendLine("    uint8_t *output,")
        appendLine("    size_t output_capacity,")
        appendLine("    ${context.moduleName}_request_handler_t handler,")
        appendLine("    void *user_data")
        appendLine(");")
        appendLine()
        appendResponseConstructors(context)
        appendLine("#ifdef __cplusplus")
        appendLine("}")
        appendLine("#endif")
        appendLine()
        appendLine("#endif")
    }

    private fun StringBuilder.appendErrorCodes(context: CContext) {
        appendLine("#define ${context.upperName}_PROTOCOL_NO_RESPONSE 0")
        appendLine("#define ${context.upperName}_PROTOCOL_ERROR_DECODE_REQUEST -1")
        appendLine("#define ${context.upperName}_PROTOCOL_ERROR_MISSING_METHOD -2")
        appendLine("#define ${context.upperName}_PROTOCOL_ERROR_MISSING_METHOD_VALUE -3")
        appendLine("#define ${context.upperName}_PROTOCOL_ERROR_INVALID_METHOD_TYPE -4")
        appendLine("#define ${context.upperName}_PROTOCOL_ERROR_UNKNOWN_METHOD -5")
        appendLine("#define ${context.upperName}_PROTOCOL_ERROR_INVALID_REQUEST -6")
        appendLine("#define ${context.upperName}_PROTOCOL_ERROR_INVALID_PROPERTY_VALUE -7")
        appendLine("#define ${context.upperName}_PROTOCOL_ERROR_RESPONSE_MISMATCH -8")
        appendLine("#define ${context.upperName}_PROTOCOL_ERROR_OUTPUT_BUFFER_TOO_SMALL -9")
        appendLine("#define ${context.upperName}_PROTOCOL_ERROR_ENCODE_RESPONSE -10")
        appendLine()
    }

    private fun StringBuilder.appendStructuredStructs(context: CContext, node: ProtocolMetaNode, path: List<String>) {
        node.children.filter { it.children.isNotEmpty() }.forEach { child ->
            appendStructuredStructs(context, child, path + child.name)
        }

        val structName = context.structName(path)
        appendLine("typedef struct $structName {")
        node.children.forEach { child ->
            val type = if (child.children.isEmpty()) {
                requireNotNull(child.scalar).cType(context)
            } else {
                "${context.structName(path + child.name)}_t"
            }
            appendLine("    $type ${child.name.toCIdentifier("field")};")
        }
        appendLine("} ${structName}_t;")
        appendLine()
    }

    private fun StringBuilder.appendRequestTypes(context: CContext) {
        appendLine("typedef enum ${context.moduleName}_request_kind {")
        context.readableProperties.forEach { appendLine("    ${context.upperName}_REQUEST_GET_${it.enumSuffix},") }
        context.writableProperties.forEach { appendLine("    ${context.upperName}_REQUEST_SET_${it.enumSuffix},") }
        appendLine("} ${context.moduleName}_request_kind_t;")
        appendLine()
        appendLine("typedef struct ${context.moduleName}_request {")
        appendLine("    ${context.moduleName}_request_kind_t kind;")
        appendLine("    union {")
        context.writableProperties.forEach { appendLine("        ${it.valueCType(context)} ${it.unionFieldName};") }
        appendLine("    } value;")
        appendLine("} ${context.moduleName}_request_t;")
        appendLine()
    }

    private fun StringBuilder.appendResponseTypes(context: CContext) {
        appendLine("typedef enum ${context.moduleName}_response_kind {")
        appendLine("    ${context.upperName}_RESPONSE_NONE = 0,")
        context.properties.forEach { appendLine("    ${context.upperName}_RESPONSE_${it.enumSuffix},") }
        appendLine("} ${context.moduleName}_response_kind_t;")
        appendLine()
        appendLine("typedef struct ${context.moduleName}_response {")
        appendLine("    ${context.moduleName}_response_kind_t kind;")
        appendLine("    union {")
        context.properties.forEach { appendLine("        ${it.valueCType(context)} ${it.unionFieldName};") }
        appendLine("    } value;")
        appendLine("} ${context.moduleName}_response_t;")
        appendLine()
    }

    private fun StringBuilder.appendResponseConstructors(context: CContext) {
        appendLine("static inline ${context.moduleName}_response_t ${context.moduleName}_no_response(void) {")
        appendLine("    ${context.moduleName}_response_t response;")
        appendLine("    response.kind = ${context.upperName}_RESPONSE_NONE;")
        appendLine("    return response;")
        appendLine("}")
        appendLine()
        context.properties.forEach { property ->
            appendLine("static inline ${context.moduleName}_response_t ${context.moduleName}_response_${property.cName}(${property.valueCType(context)} value) {")
            appendLine("    ${context.moduleName}_response_t response;")
            appendLine("    response.kind = ${context.upperName}_RESPONSE_${property.enumSuffix};")
            appendLine("    response.value.${property.unionFieldName} = value;")
            appendLine("    return response;")
            appendLine("}")
            appendLine()
        }
    }

    private fun generateSource(context: CContext): String = buildString {
        appendLine("/* Generated by controls-proto. Do not edit by hand. */")
        appendLine("#include \"${context.headerName}\"")
        appendLine()
        appendLine("#include \"pb_decode.h\"")
        appendLine("#include \"pb_encode.h\"")
        appendLine("#include \"meta.pb.h\"")
        appendLine()
        appendLine("#include <string.h>")
        appendLine()
        appendNanopbAliases(context)
        appendDecodeHelpers(context)
        appendScalarEncoders(context)
        appendEncodeNodeItem(context)
        appendStructuredDecoders(context)
        appendStructuredEncoders(context)
        appendRootDecode(context)
        appendRootEncode(context)
        appendHandleMessage(context)
    }

