    private fun StringBuilder.appendDecodeHelpers(context: CContext) {
        appendLine("static bool ${context.moduleName}_copy_c_string(char *target, size_t target_size, const char *source) {")
        appendLine("    size_t source_size = strlen(source);")
        appendLine("    if (source_size + 1u > target_size) return false;")
        appendLine("    memcpy(target, source, source_size + 1u);")
        appendLine("    return true;")
        appendLine("}")
        appendLine()
        appendLine("static bool ${context.moduleName}_copy_string_value(char *target, size_t target_size, ${context.moduleName}_string_t source) {")
        appendLine("    if (source.size + 1u > target_size) return false;")
        appendLine("    memcpy(target, source.data, source.size);")
        appendLine("    target[source.size] = '\\0';")
        appendLine("    return true;")
        appendLine("}")
        appendLine()
        appendLine("static bool ${context.moduleName}_is_key(const char *key, const char *expected) {")
        appendLine("    return strcmp(key, expected) == 0;")
        appendLine("}")
        appendLine()
        appendLine("static bool ${context.moduleName}_get_string_value(const ${context.upperName}_PROTO_META_ITEMS_ENTRY *entry, ${context.moduleName}_string_t *value) {")
        appendLine("    if (!entry->value.has_protoValue) return false;")
        appendLine("    if (entry->value.protoValue.which_value != ${context.upperName}_PROTO_VALUE_STRING_TAG) return false;")
        appendLine("    value->data = entry->value.protoValue.value.stringValue;")
        appendLine("    value->size = strlen(entry->value.protoValue.value.stringValue);")
        appendLine("    return true;")
        appendLine("}")
        appendLine()
        ProtocolScalar.values().filter { it != ProtocolScalar.STRING }.forEach { scalar ->
            appendLine("static bool ${context.moduleName}_get_${scalar.cSuffix()}_value(const ${context.upperName}_PROTO_META_ITEMS_ENTRY *entry, ${scalar.cType(context)} *value) {")
            appendLine("    if (!entry->value.has_protoValue) return false;")
            appendLine("    if (entry->value.protoValue.which_value != ${context.upperName}_PROTO_VALUE_${scalar.tagSuffix()}_TAG) return false;")
            appendLine("    *value = entry->value.protoValue.value.${scalar.protoValueField()};")
            appendLine("    return true;")
            appendLine("}")
            appendLine()
        }
    }

    private fun StringBuilder.appendStructuredDecoders(context: CContext) {
        context.properties.forEach { property ->
            val model = property.type as? ProtocolPropertyType.StructuredMeta ?: return@forEach
            appendStructuredDecodeDeclarations(context, model.model.rootNode, listOf(model.model.rootNode.name))
            appendLine()
            appendStructuredDecodeFunctions(context, model.model.rootNode, listOf(model.model.rootNode.name))
        }
    }

    private fun StringBuilder.appendStructuredDecodeDeclarations(context: CContext, node: ProtocolMetaNode, path: List<String>) {
        appendLine("static bool ${context.decodeCallbackName(path)}(pb_istream_t *stream, const pb_field_t *field, void **arg);")
        node.children.filter { it.children.isNotEmpty() }.forEach { child ->
            appendStructuredDecodeDeclarations(context, child, path + child.name)
        }
    }

    private fun StringBuilder.appendStructuredDecodeFunctions(context: CContext, node: ProtocolMetaNode, path: List<String>) {
        node.children.filter { it.children.isNotEmpty() }.forEach { child ->
            appendStructuredDecodeFunctions(context, child, path + child.name)
        }
        val typeName = "${context.structName(path)}_t"
        appendLine("typedef struct ${context.decodeContextName(path)} {")
        appendLine("    $typeName *out;")
        appendLine("} ${context.decodeContextName(path)}_t;")
        appendLine()
        appendLine("typedef struct ${context.decodeChildContextName(path)} {")
        appendLine("    $typeName *out;")
        appendLine("    const char *key;")
        appendLine("} ${context.decodeChildContextName(path)}_t;")
        appendLine()
        appendLine("static bool ${context.decodeChildCallbackName(path)}(pb_istream_t *stream, const pb_field_t *field, void **arg) {")
        appendLine("    ${context.decodeChildContextName(path)}_t *ctx = (${context.decodeChildContextName(path)}_t *)(*arg);")
        appendLine("    (void)ctx;")
        node.children.filter { it.children.isNotEmpty() }.forEach { child ->
            appendLine("    if (${context.moduleName}_is_key(ctx->key, \"${child.name}\")) {")
            appendLine("        ${context.decodeContextName(path + child.name)}_t child_ctx = { &ctx->out->${child.name.toCIdentifier("field")} };")
            appendLine("        void *child_arg = &child_ctx;")
            appendLine("        return ${context.decodeCallbackName(path + child.name)}(stream, field, &child_arg);")
            appendLine("    }")
        }
        appendLine("    (void)stream;")
        appendLine("    (void)field;")
        appendLine("    return true;")
        appendLine("}")
        appendLine()
        appendLine("static bool ${context.decodeCallbackName(path)}(pb_istream_t *stream, const pb_field_t *field, void **arg) {")
        appendLine("    (void)field;")
        appendLine("    ${context.decodeContextName(path)}_t *ctx = (${context.decodeContextName(path)}_t *)(*arg);")
        appendLine("    ${context.upperName}_PROTO_META_ITEMS_ENTRY entry = ${context.upperName}_PROTO_META_ITEMS_ENTRY_INIT_ZERO;")
        appendLine("    ${context.decodeChildContextName(path)}_t child_ctx = { ctx->out, entry.key };")
        appendLine("    entry.value.items.funcs.decode = ${context.decodeChildCallbackName(path)};")
        appendLine("    entry.value.items.arg = &child_ctx;")
        appendLine("    if (!pb_decode(stream, ${context.upperName}_PROTO_META_ITEMS_ENTRY_FIELDS, &entry)) return false;")
        node.children.forEach { child ->
            val fieldName = child.name.toCIdentifier("field")
            appendLine("    if (${context.moduleName}_is_key(entry.key, \"${child.name}\")) {")
            if (child.children.isEmpty()) {
                val scalar = requireNotNull(child.scalar)
                if (scalar == ProtocolScalar.STRING) {
                    appendLine("        ${context.moduleName}_string_t string_value;")
                    appendLine("        if (!${context.moduleName}_get_string_value(&entry, &string_value)) return false;")
                    appendLine("        ctx->out->$fieldName = string_value;")
                    appendLine("        return true;")
                } else {
                    appendLine("        return ${context.moduleName}_get_${scalar.cSuffix()}_value(&entry, &ctx->out->$fieldName);")
                }
            } else {
                appendLine("        return true;")
            }
            appendLine("    }")
        }
        appendLine("    return true;")
        appendLine("}")
        appendLine()
    }

    private fun StringBuilder.appendStructuredEncoders(context: CContext) {
        context.properties.forEach { property ->
            val model = property.type as? ProtocolPropertyType.StructuredMeta ?: return@forEach
            appendStructuredEncodeDeclarations(context, model.model.rootNode, listOf(model.model.rootNode.name))
            appendLine()
            appendStructuredEncodeFunctions(context, model.model.rootNode, listOf(model.model.rootNode.name))
        }
    }

    private fun StringBuilder.appendStructuredEncodeDeclarations(context: CContext, node: ProtocolMetaNode, path: List<String>) {
        appendLine("static bool ${context.encodeCallbackName(path)}(pb_ostream_t *stream, const pb_field_t *field, void * const *arg);")
        node.children.filter { it.children.isNotEmpty() }.forEach { child ->
            appendStructuredEncodeDeclarations(context, child, path + child.name)
        }
    }

    private fun StringBuilder.appendStructuredEncodeFunctions(context: CContext, node: ProtocolMetaNode, path: List<String>) {
        node.children.filter { it.children.isNotEmpty() }.forEach { child ->
            appendStructuredEncodeFunctions(context, child, path + child.name)
        }
        val typeName = "${context.structName(path)}_t"
        appendLine("static bool ${context.encodeCallbackName(path)}(pb_ostream_t *stream, const pb_field_t *field, void * const *arg) {")
        appendLine("    const $typeName *value = (const $typeName *)(*arg);")
        node.children.forEach { child ->
            val fieldName = child.name.toCIdentifier("field")
            if (child.children.isEmpty()) {
                appendLine("    if (!${context.encodeScalarItemName(requireNotNull(child.scalar))}(stream, field, \"${child.name}\", value->$fieldName)) return false;")
            } else {
                appendLine("    if (!${context.moduleName}_encode_node_item(stream, field, \"${child.name}\", ${context.encodeCallbackName(path + child.name)}, &value->$fieldName)) return false;")
            }
        }
        appendLine("    return true;")
        appendLine("}")
        appendLine()
    }

    private fun StringBuilder.appendRootDecode(context: CContext) {
        appendLine("typedef enum ${context.moduleName}_method {")
        appendLine("    ${context.upperName}_METHOD_NONE,")
        appendLine("    ${context.upperName}_METHOD_GET,")
        appendLine("    ${context.upperName}_METHOD_POST,")
        appendLine("    ${context.upperName}_METHOD_INVALID,")
        appendLine("} ${context.moduleName}_method_t;")
        appendLine()
        appendLine("typedef struct ${context.moduleName}_decode_context {")
        appendLine("    ${context.moduleName}_request_t request;")
        appendLine("    ${context.moduleName}_method_t method;")
        context.properties.forEach {
            appendLine("    bool ${it.hasFlagName};")
            appendLine("    bool ${it.validFlagName};")
        }
        appendLine("} ${context.moduleName}_decode_context_t;")
        appendLine()
        appendRootNestedDecode(context)
        appendLine("static bool ${context.moduleName}_decode_root_item(pb_istream_t *stream, const pb_field_t *field, void **arg) {")
        appendLine("    (void)field;")
        appendLine("    ${context.moduleName}_decode_context_t *ctx = (${context.moduleName}_decode_context_t *)(*arg);")
        appendLine("    ${context.upperName}_PROTO_META_ITEMS_ENTRY entry = ${context.upperName}_PROTO_META_ITEMS_ENTRY_INIT_ZERO;")
        appendLine("    ${context.moduleName}_root_child_decode_context_t child_ctx = { ctx, entry.key };")
        appendLine("    entry.value.items.funcs.decode = ${context.moduleName}_decode_root_child_item;")
        appendLine("    entry.value.items.arg = &child_ctx;")
        appendLine("    if (!pb_decode(stream, ${context.upperName}_PROTO_META_ITEMS_ENTRY_FIELDS, &entry)) return false;")
        appendLine("    if (${context.moduleName}_is_key(entry.key, \"$METHOD_FIELD\")) {")
        appendLine("        ${context.moduleName}_string_t method;")
        appendLine("        if (!${context.moduleName}_get_string_value(&entry, &method)) {")
        appendLine("            ctx->method = ${context.upperName}_METHOD_INVALID;")
        appendLine("            return true;")
        appendLine("        }")
        appendLine("        if (method.size == 3u && memcmp(method.data, \"$GET_METHOD\", 3u) == 0) ctx->method = ${context.upperName}_METHOD_GET;")
        appendLine("        else if (method.size == 4u && memcmp(method.data, \"$POST_METHOD\", 4u) == 0) ctx->method = ${context.upperName}_METHOD_POST;")
        appendLine("        else ctx->method = ${context.upperName}_METHOD_INVALID;")
        appendLine("        return true;")
        appendLine("    }")
        context.properties.forEach { property ->
            appendLine("    if (${context.moduleName}_is_key(entry.key, \"${property.name}\")) {")
            appendLine("        ctx->${property.hasFlagName} = true;")
            when (val type = property.type) {
                is ProtocolPropertyType.Scalar -> {
                    if (property.writable) {
                        if (type.scalar == ProtocolScalar.STRING) {
                            appendLine("        /* String scalar POST values are exposed as borrowed data from the decoded packet. */")
                            appendLine("        ctx->${property.validFlagName} = ${context.moduleName}_get_string_value(&entry, &ctx->request.value.${property.unionFieldName});")
                        } else {
                            appendLine("        ctx->${property.validFlagName} = ${context.moduleName}_get_${type.scalar.cSuffix()}_value(&entry, &ctx->request.value.${property.unionFieldName});")
                        }
                    } else {
                        appendLine("        ctx->${property.validFlagName} = true;")
                    }
                }
                is ProtocolPropertyType.StructuredMeta -> {
                    appendLine("        ctx->${property.validFlagName} = true;")
                }
            }
            appendLine("        return true;")
            appendLine("    }")
        }
        appendLine("    return true;")
        appendLine("}")
        appendLine()
        appendLine("static int ${context.moduleName}_decode_host_request(const uint8_t *input, size_t input_size, ${context.moduleName}_request_t *request) {")
        appendLine("    ${context.upperName}_PROTO_ENVELOPE envelope = ${context.upperName}_PROTO_ENVELOPE_INIT_ZERO;")
        appendLine("    ${context.moduleName}_decode_context_t ctx;")
        appendLine("    memset(&ctx, 0, sizeof(ctx));")
        appendLine("    envelope.meta.items.funcs.decode = ${context.moduleName}_decode_root_item;")
        appendLine("    envelope.meta.items.arg = &ctx;")
        appendLine("    pb_istream_t stream = pb_istream_from_buffer(input, input_size);")
        appendLine("    if (!pb_decode(&stream, ${context.upperName}_PROTO_ENVELOPE_FIELDS, &envelope)) return ${context.upperName}_PROTOCOL_ERROR_DECODE_REQUEST;")
        appendLine("    if (!envelope.has_meta) return ${context.upperName}_PROTOCOL_ERROR_DECODE_REQUEST;")
        appendLine("    if (ctx.method == ${context.upperName}_METHOD_NONE) return ${context.upperName}_PROTOCOL_ERROR_MISSING_METHOD;")
        appendLine("    if (ctx.method == ${context.upperName}_METHOD_INVALID) return ${context.upperName}_PROTOCOL_ERROR_UNKNOWN_METHOD;")
        appendLine("    if (ctx.method == ${context.upperName}_METHOD_GET) {")
        context.readableProperties.forEach {
            appendLine("        if (ctx.${it.hasFlagName}) { request->kind = ${context.upperName}_REQUEST_GET_${it.enumSuffix}; *request = ctx.request; request->kind = ${context.upperName}_REQUEST_GET_${it.enumSuffix}; return 1; }")
        }
        appendLine("        return ${context.upperName}_PROTOCOL_ERROR_INVALID_REQUEST;")
        appendLine("    }")
        appendLine("    if (ctx.method == ${context.upperName}_METHOD_POST) {")
        context.writableProperties.forEach {
            appendLine("        if (ctx.${it.hasFlagName}) {")
            appendLine("            if (!ctx.${it.validFlagName}) return ${context.upperName}_PROTOCOL_ERROR_INVALID_PROPERTY_VALUE;")
            appendLine("            *request = ctx.request;")
            appendLine("            request->kind = ${context.upperName}_REQUEST_SET_${it.enumSuffix};")
            appendLine("            return 1;")
            appendLine("        }")
        }
        appendLine("        return ${context.upperName}_PROTOCOL_ERROR_INVALID_REQUEST;")
        appendLine("    }")
        appendLine("    return ${context.upperName}_PROTOCOL_ERROR_UNKNOWN_METHOD;")
        appendLine("}")
        appendLine()
    }

    private fun StringBuilder.appendRootNestedDecode(context: CContext) {
        appendLine("typedef struct ${context.moduleName}_root_child_decode_context {")
        appendLine("    ${context.moduleName}_decode_context_t *root;")
        appendLine("    const char *key;")
        appendLine("} ${context.moduleName}_root_child_decode_context_t;")
        appendLine()
        appendLine("static bool ${context.moduleName}_decode_root_child_item(pb_istream_t *stream, const pb_field_t *field, void **arg) {")
        appendLine("    ${context.moduleName}_root_child_decode_context_t *ctx = (${context.moduleName}_root_child_decode_context_t *)(*arg);")
        context.properties.forEach { property ->
            val model = property.type as? ProtocolPropertyType.StructuredMeta ?: return@forEach
            appendLine("    if (${context.moduleName}_is_key(ctx->key, \"${property.name}\")) {")
            appendLine("        ${context.decodeContextName(listOf(model.model.rootNode.name))}_t child_ctx = { &ctx->root->request.value.${property.unionFieldName} };")
            appendLine("        void *child_arg = &child_ctx;")
            appendLine("        return ${context.decodeCallbackName(listOf(model.model.rootNode.name))}(stream, field, &child_arg);")
            appendLine("    }")
        }
        appendLine("    (void)stream;")
        appendLine("    (void)field;")
        appendLine("    return true;")
        appendLine("}")
        appendLine()
    }

    private fun StringBuilder.appendRootEncode(context: CContext) {
        appendLine("typedef struct ${context.moduleName}_encode_context {")
        appendLine("    const char *method;")
        appendLine("    const ${context.moduleName}_response_t *response;")
        appendLine("} ${context.moduleName}_encode_context_t;")
        appendLine()
        appendLine("static bool ${context.moduleName}_encode_root_items(pb_ostream_t *stream, const pb_field_t *field, void * const *arg) {")
        appendLine("    const ${context.moduleName}_encode_context_t *ctx = (const ${context.moduleName}_encode_context_t *)(*arg);")
        appendLine("    if (!${context.moduleName}_encode_cstr_item(stream, field, \"$METHOD_FIELD\", ctx->method)) return false;")
        appendLine("    switch (ctx->response->kind) {")
        context.properties.forEach { property ->
            appendLine("    case ${context.upperName}_RESPONSE_${property.enumSuffix}:")
            when (val type = property.type) {
                is ProtocolPropertyType.Scalar -> {
                    appendLine("        return ${context.encodeScalarItemName(type.scalar)}(stream, field, \"${property.name}\", ctx->response->value.${property.unionFieldName});")
                }
                is ProtocolPropertyType.StructuredMeta -> {
                    appendLine("        return ${context.moduleName}_encode_node_item(stream, field, \"${property.name}\", ${context.encodeCallbackName(listOf(type.model.rootNode.name))}, &ctx->response->value.${property.unionFieldName});")
                }
            }
        }
        appendLine("    default:")
        appendLine("        return false;")
        appendLine("    }")
        appendLine("}")
        appendLine()
        appendLine("static int ${context.moduleName}_write_response_message(const char *method, const ${context.moduleName}_response_t *response, uint8_t *output, size_t output_capacity) {")
        appendLine("    ${context.upperName}_PROTO_ENVELOPE envelope = ${context.upperName}_PROTO_ENVELOPE_INIT_ZERO;")
        appendLine("    ${context.moduleName}_encode_context_t ctx = { method, response };")
        appendLine("    envelope.has_meta = true;")
        appendLine("    envelope.meta.items.funcs.encode = ${context.moduleName}_encode_root_items;")
        appendLine("    envelope.meta.items.arg = &ctx;")
        appendLine("    pb_ostream_t stream = pb_ostream_from_buffer(output, output_capacity);")
        appendLine("    if (!pb_encode(&stream, ${context.upperName}_PROTO_ENVELOPE_FIELDS, &envelope)) return ${context.upperName}_PROTOCOL_ERROR_ENCODE_RESPONSE;")
        appendLine("    return (int)stream.bytes_written;")
        appendLine("}")
        appendLine()
        appendLine("static int ${context.moduleName}_encode_host_response(const ${context.moduleName}_request_t *request, const ${context.moduleName}_response_t *response, uint8_t *output, size_t output_capacity) {")
        appendLine("    (void)output_capacity;")
        appendLine("    switch (request->kind) {")
        context.readableProperties.forEach {
            appendLine("    case ${context.upperName}_REQUEST_GET_${it.enumSuffix}:")
            appendLine("        if (response->kind != ${context.upperName}_RESPONSE_${it.enumSuffix}) return ${context.upperName}_PROTOCOL_ERROR_RESPONSE_MISMATCH;")
            appendLine("        return ${context.moduleName}_write_response_message(\"$GET_METHOD\", response, output, output_capacity);")
        }
        context.writableProperties.forEach {
            appendLine("    case ${context.upperName}_REQUEST_SET_${it.enumSuffix}:")
            appendLine("        if (response->kind != ${context.upperName}_RESPONSE_${it.enumSuffix}) return ${context.upperName}_PROTOCOL_ERROR_RESPONSE_MISMATCH;")
            appendLine("        return ${context.moduleName}_write_response_message(\"$POST_METHOD\", response, output, output_capacity);")
        }
        appendLine("    default:")
        appendLine("        return ${context.upperName}_PROTOCOL_ERROR_RESPONSE_MISMATCH;")
        appendLine("    }")
        appendLine("}")
        appendLine()
    }

    private fun StringBuilder.appendEncodeNodeItem(context: CContext) {
        appendLine("static bool ${context.moduleName}_encode_node_item(")
        appendLine("    pb_ostream_t *stream,")
        appendLine("    const pb_field_t *field,")
        appendLine("    const char *key,")
        appendLine("    bool (*items_encoder)(pb_ostream_t *, const pb_field_t *, void * const *),")
        appendLine("    const void *value")
        appendLine(") {")
        appendLine("    ${context.upperName}_PROTO_META_ITEMS_ENTRY entry = ${context.upperName}_PROTO_META_ITEMS_ENTRY_INIT_ZERO;")
        appendLine("    if (!${context.moduleName}_copy_c_string(entry.key, sizeof(entry.key), key)) return false;")
        appendLine("    entry.has_value = true;")
        appendLine("    entry.value.items.funcs.encode = items_encoder;")
        appendLine("    entry.value.items.arg = (void *)value;")
        appendLine("    return pb_encode_tag_for_field(stream, field) && pb_encode_submessage(stream, ${context.upperName}_PROTO_META_ITEMS_ENTRY_FIELDS, &entry);")
        appendLine("}")
        appendLine()
    }

    private fun StringBuilder.appendScalarEncoders(context: CContext) {
        appendLine("static bool ${context.moduleName}_encode_string_item(pb_ostream_t *stream, const pb_field_t *field, const char *key, ${context.moduleName}_string_t value) {")
        appendLine("    ${context.upperName}_PROTO_META_ITEMS_ENTRY entry = ${context.upperName}_PROTO_META_ITEMS_ENTRY_INIT_ZERO;")
        appendLine("    if (!${context.moduleName}_copy_c_string(entry.key, sizeof(entry.key), key)) return false;")
        appendLine("    entry.has_value = true;")
        appendLine("    entry.value.has_protoValue = true;")
        appendLine("    entry.value.protoValue.which_value = ${context.upperName}_PROTO_VALUE_STRING_TAG;")
        appendLine("    if (!${context.moduleName}_copy_string_value(entry.value.protoValue.value.stringValue, sizeof(entry.value.protoValue.value.stringValue), value)) return false;")
        appendLine("    return pb_encode_tag_for_field(stream, field) && pb_encode_submessage(stream, ${context.upperName}_PROTO_META_ITEMS_ENTRY_FIELDS, &entry);")
        appendLine("}")
        appendLine()
        appendLine("static bool ${context.moduleName}_encode_cstr_item(pb_ostream_t *stream, const pb_field_t *field, const char *key, const char *value) {")
        appendLine("    ${context.moduleName}_string_t string_value = { value, strlen(value) };")
        appendLine("    return ${context.moduleName}_encode_string_item(stream, field, key, string_value);")
        appendLine("}")
        appendLine()
        ProtocolScalar.values().filter { it != ProtocolScalar.STRING }.forEach { scalar ->
            appendLine("static bool ${context.encodeScalarItemName(scalar)}(pb_ostream_t *stream, const pb_field_t *field, const char *key, ${scalar.cType(context)} value) {")
            appendLine("    ${context.upperName}_PROTO_META_ITEMS_ENTRY entry = ${context.upperName}_PROTO_META_ITEMS_ENTRY_INIT_ZERO;")
            appendLine("    if (!${context.moduleName}_copy_c_string(entry.key, sizeof(entry.key), key)) return false;")
            appendLine("    entry.has_value = true;")
            appendLine("    entry.value.has_protoValue = true;")
            appendLine("    entry.value.protoValue.which_value = ${context.upperName}_PROTO_VALUE_${scalar.tagSuffix()}_TAG;")
            appendLine("    entry.value.protoValue.value.${scalar.protoValueField()} = value;")
            appendLine("    return pb_encode_tag_for_field(stream, field) && pb_encode_submessage(stream, ${context.upperName}_PROTO_META_ITEMS_ENTRY_FIELDS, &entry);")
            appendLine("}")
            appendLine()
        }
    }

    private fun StringBuilder.appendHandleMessage(context: CContext) {
        appendLine("int ${context.moduleName}_handle_message(")
        appendLine("    const uint8_t *input,")
        appendLine("    size_t input_size,")
        appendLine("    uint8_t *output,")
        appendLine("    size_t output_capacity,")
        appendLine("    ${context.moduleName}_request_handler_t handler,")
        appendLine("    void *user_data")
        appendLine(") {")
        appendLine("    if (input == NULL || output == NULL || handler == NULL) return ${context.upperName}_PROTOCOL_ERROR_DECODE_REQUEST;")
        appendLine("    ${context.moduleName}_request_t request;")
        appendLine("    int decode_status = ${context.moduleName}_decode_host_request(input, input_size, &request);")
        appendLine("    if (decode_status < 0) return decode_status;")
        appendLine("    ${context.moduleName}_response_t response = handler(&request, user_data);")
        appendLine("    if (response.kind == ${context.upperName}_RESPONSE_NONE) return ${context.upperName}_PROTOCOL_NO_RESPONSE;")
        appendLine("    return ${context.moduleName}_encode_host_response(&request, &response, output, output_capacity);")
        appendLine("}")
    }

