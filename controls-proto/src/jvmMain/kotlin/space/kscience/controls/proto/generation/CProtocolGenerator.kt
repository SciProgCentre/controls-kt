    private fun CPropertyInfo.valueCType(context: CContext): String = when (val propertyType = type) {
        is ProtocolPropertyType.Scalar -> propertyType.scalar.cType(context)
        is ProtocolPropertyType.StructuredMeta -> requireNotNull(rootStructName)
    }

    private fun ProtocolScalar.cType(context: CContext): String = when (this) {
        ProtocolScalar.INT32 -> "int32_t"
        ProtocolScalar.INT64 -> "int64_t"
        ProtocolScalar.FLOAT32 -> "float"
        ProtocolScalar.FLOAT64 -> "double"
        ProtocolScalar.BOOLEAN -> "bool"
        ProtocolScalar.STRING -> "${context.moduleName}_string_t"
    }

    private fun ProtocolScalar.cSuffix(): String = when (this) {
        ProtocolScalar.INT32 -> "i32"
        ProtocolScalar.INT64 -> "i64"
        ProtocolScalar.FLOAT32 -> "float"
        ProtocolScalar.FLOAT64 -> "double"
        ProtocolScalar.BOOLEAN -> "bool"
        ProtocolScalar.STRING -> "string"
    }

