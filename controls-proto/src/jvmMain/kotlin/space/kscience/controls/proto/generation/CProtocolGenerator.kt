package space.kscience.controls.proto.generation

import space.kscience.controls.spec.DeviceSpec

public data class CBackendOptions(
    val protoSources: List<ProtocolProtoSource> = listOf(ProtocolProtoSources.bundledDataForgeMeta()),
    val nanopbTextMaxLength: Int = 63,
) : ProtocolBackendOptions {
    init {
        require(nanopbTextMaxLength > 0) { "nanopb text max length must be positive" }
    }
}

public object CProtocolGenerator : ProtocolGenerator {
    override val language: ProtocolLanguage get() = ProtocolLanguage.C

    private const val METHOD_FIELD = "method"
    private const val GET_METHOD = "GET"
    private const val POST_METHOD = "POST"

    private data class CContext(
        val moduleName: String,
        val includeGuard: String,
        val headerName: String,
        val sourceName: String,
        val optionsName: String,
        val textMaxLength: Int,
        val properties: List<CPropertyInfo>,
    ) {
        val readableProperties: List<CPropertyInfo> get() = properties.filter { it.readable }
        val writableProperties: List<CPropertyInfo> get() = properties.filter { it.writable }
        val upperName: String get() = moduleName.uppercase()
    }

    private data class CPropertyInfo(
        val name: String,
        val cName: String,
        val enumSuffix: String,
        val type: ProtocolPropertyType,
        val readable: Boolean,
        val writable: Boolean,
        val rootStructName: String?,
    ) {
        val unionFieldName: String get() = cName
        val hasFlagName: String get() = "has_$cName"
        val validFlagName: String get() = "valid_$cName"
    }

    override fun generate(
        deviceSpec: DeviceSpec<*>,
        options: ProtocolGenerationOptions,
    ): GeneratedProtocolPackage {
        val backendOptions = options.cBackendOptions()
        val context = deviceSpec.cGenerationContext(options.moduleName, backendOptions)
        val protoFiles = backendOptions.protoSources.map { it.load() }

        return GeneratedProtocolPackage(
            language = language,
            files = protoFiles + listOf(
                GeneratedProtocolFile("proto/${context.optionsName}", generateNanopbOptions(context)),
                GeneratedProtocolFile("CMakeLists.txt", generateCMakeLists(context)),
                GeneratedProtocolFile(context.headerName, generateHeader(context)),
                GeneratedProtocolFile(context.sourceName, generateSource(context)),
                GeneratedProtocolFile("README.md", generateReadme(context, protoFiles)),
            ),
        )
    }

    private fun ProtocolGenerationOptions.cBackendOptions(): CBackendOptions = when (val backendOptions = backend) {
        is CBackendOptions -> backendOptions
        DefaultProtocolBackendOptions -> CBackendOptions()
        else -> error("C generator does not accept backend options: ${backendOptions::class.simpleName}")
    }

    private fun DeviceSpec<*>.cGenerationContext(moduleName: String, options: CBackendOptions): CContext {
        val cModuleName = moduleName.toCIdentifier("device")
        val properties = toProtocolSchema().properties.map { property ->
            val cName = property.name.toCIdentifier("property")
            CPropertyInfo(
                name = property.name,
                cName = cName,
                enumSuffix = cName.uppercase(),
                type = property.type,
                readable = property.readable,
                writable = property.writable,
                rootStructName = when (property.type) {
                    is ProtocolPropertyType.Scalar -> null
                    is ProtocolPropertyType.StructuredMeta -> "${cModuleName}_${cName}_t"
                },
            )
        }
        return CContext(
            moduleName = cModuleName,
            includeGuard = "${cModuleName.uppercase()}_PROTOCOL_H",
            headerName = "${cModuleName}_protocol.h",
            sourceName = "${cModuleName}_protocol.c",
            optionsName = "meta.options",
            textMaxLength = options.nanopbTextMaxLength,
            properties = properties,
        )
    }

