        ProtocolScalar.INT32 -> "I32"
        ProtocolScalar.INT64 -> "I64"
        ProtocolScalar.FLOAT32 -> "FLOAT"
        ProtocolScalar.FLOAT64 -> "DOUBLE"
        ProtocolScalar.BOOLEAN -> "BOOL"
        ProtocolScalar.STRING -> "STRING"
    }

