#
# Keep recursive ProtoMeta.items as callbacks. This avoids impossible recursive
# by-value C structs and lets protocol code decode only requested fields.
*.ProtoMeta.items type:FT_CALLBACK

# Generated C code expects fixed C strings for map keys and string values.
*.ProtoMeta.ItemsEntry.key max_length:${context.textMaxLength}
*.ProtoMeta.ProtoValue.stringValue max_length:${context.textMaxLength}

# The device protocol currently uses only envelope.meta. Payload bytes and list
# value variants are ignored by the generated MCU handler.
*.ProtoEnvelope.dataBytes type:FT_IGNORE
*.ProtoMeta.ProtoValue.bytesValue type:FT_IGNORE
*.ProtoMeta.ProtoValue.listValue type:FT_IGNORE
*.ProtoMeta.ProtoValue.float64ListValue type:FT_IGNORE
""".trimIndent() + "\n"

