        ProtocolScalar.INT32 -> "int32Value"
        ProtocolScalar.INT64 -> "int64Value"
        ProtocolScalar.FLOAT32 -> "floatValue"
        ProtocolScalar.FLOAT64 -> "doubleValue"
        ProtocolScalar.BOOLEAN -> "booleanValue"
